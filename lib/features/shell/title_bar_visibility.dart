import 'package:flutter/foundation.dart';

/// Видна ли своя шапка окна (см. `window_title_bar.dart`).
///
/// Флаг нужен потому, что шапка нарисована в `app.dart` **выше** навигатора:
/// экран клипа её не видит и не может спрятать из своего дерева. Поэтому
/// полноэкранный клип гасит шапку через это значение, а `app.dart` на него
/// подписан и убирает панель из раскладки.
///
/// Это [ValueNotifier], а не провайдер: состояние чисто интерфейсное, а
/// значение одно на всё приложение — полноэкранный клип в каждый момент один.
final ValueNotifier<bool> titleBarVisible = ValueNotifier<bool>(true);
